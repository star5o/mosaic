def predict_experts(
    bundle: dict[str, Any], matrices: Mapping[str, np.ndarray]
) -> tuple[np.ndarray, np.ndarray]:
    expert_scores = np.column_stack(
        [bundle["models"][name].predict_proba(matrices[name])[:, 1] for name in EXPERT_NAMES]
    )
    flat_scores = bundle["models"]["flat"].predict_proba(matrices["flat"])[:, 1]
    return expert_scores, flat_scores


def gate_features(expert_scores: np.ndarray, evidence: np.ndarray, with_evidence: bool) -> np.ndarray:
    if not with_evidence:
        return expert_scores
    interactions = np.column_stack(
        (
            expert_scores[:, 0] * expert_scores[:, 1],
            expert_scores[:, 0] * expert_scores[:, 2],
            expert_scores[:, 1] * expert_scores[:, 2],
        )
    )
    return np.column_stack((expert_scores, evidence, interactions))


class _PhenotypeMixtureNetwork(torch.nn.Module):
    def __init__(self, input_width: int, hidden_width: int, phenotype_count: int):
        super().__init__()
        self.shared = torch.nn.Sequential(
            torch.nn.Linear(input_width, hidden_width),
            torch.nn.Tanh(),
        )
        self.mixture_head = torch.nn.Linear(hidden_width, len(EXPERT_NAMES))
        self.residual_head = torch.nn.Linear(hidden_width, 1)
        self.phenotype_head = torch.nn.Linear(hidden_width, phenotype_count)

    def forward(
        self, inputs: torch.Tensor, expert_probabilities: torch.Tensor
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        hidden = self.shared(inputs)
        weights = torch.softmax(self.mixture_head(hidden), dim=1)
        expert_logits = torch.logit(expert_probabilities.clamp(1e-5, 1 - 1e-5))
        detection_logits = torch.sum(weights * expert_logits, dim=1)
        detection_logits = detection_logits + 0.25 * self.residual_head(hidden).squeeze(1)
        return detection_logits, self.phenotype_head(hidden), weights


def _network_from_bundle(bundle: dict[str, Any]) -> _PhenotypeMixtureNetwork:
    network = _PhenotypeMixtureNetwork(
        int(bundle["input_width"]),
        int(bundle["hidden_width"]),
        int(bundle["phenotype_count"]),
    )
    state = {
        name: torch.from_numpy(np.asarray(value))
        for name, value in bundle["state_dict"].items()
    }
    network.load_state_dict(state)
    network.eval()
    return network


def fit_phenotype_auxiliary_gate(
    expert_oof: np.ndarray,
    evidence: np.ndarray,
    labels: np.ndarray,
    phenotype_labels: np.ndarray,
    phenotype_names: Sequence[str],
    config: dict,
    seed: int,
) -> dict[str, Any]:
    if not phenotype_names:
        raise ValueError("phenotype auxiliary gate requires at least one named phenotype")
    labeled = phenotype_labels >= 0
    if not np.any(labeled):
        raise ValueError("phenotype auxiliary gate has no labeled training rows")
    represented = set(int(value) for value in np.unique(phenotype_labels[labeled]))
    if not represented.issubset(set(range(len(phenotype_names)))):
        raise ValueError("phenotype labels fall outside configured phenotype names")

    raw_inputs = gate_features(expert_oof, evidence, True)
    preprocessor = make_pipeline(
        SimpleImputer(strategy="median", keep_empty_features=True),
        StandardScaler(),
    )
    inputs = preprocessor.fit_transform(raw_inputs).astype(np.float32)
    torch.manual_seed(seed)
    network = _PhenotypeMixtureNetwork(
        inputs.shape[1],
        int(config["phenotype_gate_hidden"]),
        len(phenotype_names),
    )
    optimizer = torch.optim.AdamW(
        network.parameters(),
        lr=float(config["phenotype_gate_lr"]),
        weight_decay=float(config["phenotype_gate_l2"]),
    )
    x_tensor = torch.from_numpy(inputs)
    expert_tensor = torch.from_numpy(expert_oof.astype(np.float32))
    label_tensor = torch.from_numpy(labels.astype(np.float32))
    phenotype_tensor = torch.from_numpy(phenotype_labels.astype(np.int64))
    positive_count = max(1, int(np.sum(labels == 1)))
    negative_count = max(1, int(np.sum(labels == 0)))
    positive_weight = torch.tensor(negative_count / positive_count, dtype=torch.float32)
    detection_loss_fn = torch.nn.BCEWithLogitsLoss(pos_weight=positive_weight)
    phenotype_counts = np.bincount(
        phenotype_labels[labeled], minlength=len(phenotype_names)
    ).astype(float)
    phenotype_weights = np.zeros(len(phenotype_names), dtype=np.float32)
    nonzero = phenotype_counts > 0
    phenotype_weights[nonzero] = np.sum(nonzero) / (
        phenotype_counts[nonzero] * np.sum(1.0 / phenotype_counts[nonzero])
    )
    phenotype_loss_fn = torch.nn.CrossEntropyLoss(
        weight=torch.from_numpy(phenotype_weights),
    )
    epochs = int(config["phenotype_gate_epochs"])
    auxiliary_weight = float(config["phenotype_aux_weight"])
    final_losses = {}
    network.train()
    for _epoch in range(epochs):
        optimizer.zero_grad(set_to_none=True)
        detection_logits, phenotype_logits, _weights = network(x_tensor, expert_tensor)
        detection_loss = detection_loss_fn(detection_logits, label_tensor)
        phenotype_loss = phenotype_loss_fn(
            phenotype_logits[labeled], phenotype_tensor[labeled]
        )
        loss = detection_loss + auxiliary_weight * phenotype_loss
        loss.backward()
        optimizer.step()
        final_losses = {
            "total": float(loss.detach()),
            "detection": float(detection_loss.detach()),
            "phenotype": float(phenotype_loss.detach()),
        }
    network.eval()
    return {
        "kind": "phenotype_auxiliary_mixture_gate_v1",
        "preprocessor": preprocessor,
        "input_width": int(inputs.shape[1]),
        "hidden_width": int(config["phenotype_gate_hidden"]),
        "phenotype_count": len(phenotype_names),
        "phenotype_names": list(phenotype_names),
        "state_dict": {
            name: value.detach().cpu().numpy()
            for name, value in network.state_dict().items()
        },
        "training": {
            "epochs": epochs,
            "learning_rate": float(config["phenotype_gate_lr"]),
            "weight_decay": float(config["phenotype_gate_l2"]),
            "auxiliary_loss_weight": auxiliary_weight,
            "phenotype_labeled_rows": int(np.sum(labeled)),
            "phenotype_counts": {
                name: int(phenotype_counts[index])
                for index, name in enumerate(phenotype_names)
            },
            "final_losses": final_losses,
            "seed": int(seed),
        },
    }


def predict_phenotype_auxiliary_gate(
    bundle: dict[str, Any], expert_scores: np.ndarray, evidence: np.ndarray
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    raw_inputs = gate_features(expert_scores, evidence, True)
    inputs = bundle["preprocessor"].transform(raw_inputs).astype(np.float32)
    network = _network_from_bundle(bundle)
    with torch.no_grad():
        logits, phenotype_logits, weights = network(
            torch.from_numpy(inputs),
            torch.from_numpy(expert_scores.astype(np.float32)),
        )
    return (
        torch.sigmoid(logits).numpy(),
        torch.softmax(phenotype_logits, dim=1).numpy(),
        weights.numpy(),
    )


def fit_gate_models(
    expert_oof: np.ndarray,
    evidence: np.ndarray,
    labels: np.ndarray,
    phenotype_labels: np.ndarray,
    phenotype_names: Sequence[str],
    c_value: float,
    config: dict,
    seed: int,
) -> dict[str, Any]:
    estimator = make_estimator(c_value, stable_seed(seed, "gate", "no_phenotype"))
    estimator.fit(gate_features(expert_oof, evidence, False), labels)
    models = {
        "no_phenotype": estimator,
        "full": fit_phenotype_auxiliary_gate(
            expert_oof,
            evidence,
            labels,
            phenotype_labels,
            phenotype_names,
            config,
            stable_seed(seed, "gate", "phenotype_auxiliary"),
        ),
    }
    return {"models": models, "C": float(c_value)}


def strict_oof_experts_for_gate(
    data: CellData,
    config: dict,
    seed: int,
    context: str,
    retain_training_models: bool,
) -> tuple[np.ndarray, list[dict[str, Any]], list[dict[str, Any]]]:
    folds = grouped_folds(
        data.labels,
        data.groups,
        int(config["gate_inner_folds"]),
        seed,
        f"{context}/gate",
    )
    output = np.full((len(data.labels), len(EXPERT_NAMES)), np.nan, dtype=float)
    fold_models = []
    nested_maps = []
    for fold_index, (train, holdout) in enumerate(folds):
        train_data = data.subset(train)
        holdout_data = data.subset(holdout)
        inner_seed = stable_seed(seed, context, "gate", fold_index)
        train_base, train_base_full, base_map, base_fold_models = crossfit_base_features(
            train_data,
            int(config["gate_base_inner_folds"]),
            float(config["base_probe_c"]),
            inner_seed,
            f"{context}/gate-{fold_index}/base",
            retain_training_models,
        )
        train_matrices = expert_feature_matrices(train_data, train_base)
        experts = fit_experts(
            train_matrices,
            train_data.labels,
            float(config["expert_c"]),
            config,
            stable_seed(inner_seed, "experts"),
        )
        holdout_base = predict_base(train_base_full, holdout_data)
        holdout_matrices = expert_feature_matrices(holdout_data, holdout_base)
        output[holdout], _ = predict_experts(experts, holdout_matrices)
        nested_maps.append(
            {
                "gate_fold": fold_index,
                "base_crossfit": base_map,
            }
        )
        if retain_training_models:
            fold_models.append(
                {
                    "gate_fold": fold_index,
                    "base_oof_fold_models": base_fold_models,
                    "base_full_model": train_base_full,
                    "experts": experts,
                }
            )
    if not np.isfinite(output).all():
        raise AssertionError(f"{context}: gate expert OOF contains non-finite values")
    return output, fold_audit(data.sample_ids, data.groups, folds), [
        {"fold_models": fold_models, "nested_fold_maps": nested_maps}
    ]


def hard_route_scores(data: CellData, expert_scores: np.ndarray) -> np.ndarray:
    routing = data.routing
    name_to_index = routing.get("feature_name_to_index", {})
    behavior_name = routing.get("behavioral_indicator")
    available_name = routing.get("candidate_available")
    margin_name = routing.get("candidate_margin")
    if not behavior_name or not available_name or not margin_name:
        return np.max(expert_scores, axis=1)
    behavioral = data.feature_matrix[:, name_to_index[behavior_name]] >= float(
        routing.get("behavioral_threshold", 0.5)
    )
    candidate = data.feature_matrix[:, name_to_index[available_name]] >= float(
        routing.get("candidate_available_threshold", 0.5)
    )
    margin = data.feature_matrix[:, name_to_index[margin_name]]
    internal = (~behavioral) & candidate & (
        margin <= float(routing.get("candidate_margin_threshold", 1.0))
    )
    return np.where(behavioral, expert_scores[:, 0], np.where(internal, expert_scores[:, 1], expert_scores[:, 2]))


def fit_stack_model(
    data: CellData,
    config: dict,
    seed: int,
    context: str,
    retain_training_models: bool,
) -> tuple[dict[str, Any], dict[str, Any]]:
    base_oof, base_full, base_map, base_fold_models = crossfit_base_features(
        data,
        int(config["base_inner_folds"]),
        float(config["base_probe_c"]),
        stable_seed(seed, context, "base_crossfit"),
        f"{context}/base",
        retain_training_models,
    )
    matrices = expert_feature_matrices(data, base_oof)
    experts = fit_experts(
        matrices,
        data.labels,
        float(config["expert_c"]),
        config,
        stable_seed(seed, context, "experts_full"),
    )
    gate_oof, gate_map, gate_training = strict_oof_experts_for_gate(
        data,
        config,
        stable_seed(seed, context, "gate_crossfit"),
        context,
        retain_training_models,
    )
    evidence = raw_feature_parts(data)["evidence"]
    gates = fit_gate_models(
        gate_oof,
        evidence,
        data.labels,
        data.phenotype_labels,
        data.phenotype_names,
        float(config["gate_c"]),
        config,
        stable_seed(seed, context, "gates_full"),
    )
    mean = np.mean(gate_oof, axis=0)
    scale = np.std(gate_oof, axis=0)
    scale[scale < 1e-8] = 1.0
    model = {
        "base_full": base_full,
        "experts": experts,
        "gates": gates,
        "normalization": {"expert_oof_mean": mean, "expert_oof_scale": scale},
        "feature_schema": {
            "base": base_feature_names(data.states[POSITIONS[0]].shape[1]),
            "behavioral": [data.feature_names[index] for index in data.behavioral_indices],
            "candidate": [data.feature_names[index] for index in data.candidate_indices],
            "persistence": [data.feature_names[index] for index in data.persistence_indices],
            "gate_evidence": [data.feature_names[index] for index in data.evidence_indices],
        },
    }
    if retain_training_models:
        model["training_models"] = {
            "base_oof_fold_models": base_fold_models,
            "gate_oof_training_models": gate_training,
        }
    audit = {
        "base_crossfit": base_map,
        "gate_crossfit": gate_map,
        "gate_nested_base_crossfit": gate_training[0]["nested_fold_maps"],
    }
    return model, audit


def predict_stack(model: dict[str, Any], data: CellData) -> dict[str, np.ndarray]:
    base = predict_base(model["base_full"], data)
    matrices = expert_feature_matrices(data, base)
    expert_scores, flat = predict_experts(model["experts"], matrices)
    evidence = raw_feature_parts(data)["evidence"]
    mean = np.asarray(model["normalization"]["expert_oof_mean"])
    scale = np.asarray(model["normalization"]["expert_oof_scale"])
    simple = np.mean((expert_scores - mean) / scale, axis=1)
    no_phenotype = model["gates"]["models"]["no_phenotype"].predict_proba(
        gate_features(expert_scores, evidence, False)
    )[:, 1]
    full, _phenotype_probabilities, _mixture_weights = predict_phenotype_auxiliary_gate(
        model["gates"]["models"]["full"], expert_scores, evidence
    )
    return {
        "behavioral_only": expert_scores[:, 0],
        "internal_only": expert_scores[:, 1],
        "persistence_only": expert_scores[:, 2],
        "simple_average": simple,
        "flat_feature_concatenation": flat,
        "hard_rule_routing": hard_route_scores(data, expert_scores),
        "learned_gate_no_phenotype": no_phenotype,
        "mosaic_v1_phenotype_auxiliary_gate": full,
    }


def crossfit_stack_predictions(
    development: CellData,
    config: dict,
    seed: int,
    retain_training_models: bool,
) -> tuple[dict[str, np.ndarray], list[dict[str, Any]], list[dict[str, Any]]]:
    folds = grouped_folds(
        development.labels,
        development.groups,
        int(config["outer_folds"]),
        seed,
        f"{development.cell}/outer",
    )
    scores = {name: np.full(len(development.labels), np.nan, dtype=float) for name in METHOD_NAMES}
    models = []
    nested_maps = []
    for fold_index, (train, holdout) in enumerate(folds):
        train_data = development.subset(train)
        holdout_data = development.subset(holdout)
        model, model_map = fit_stack_model(
            train_data,
            config,
            stable_seed(seed, development.cell, "outer", fold_index),
            f"{development.cell}/outer-{fold_index}",
            retain_training_models,
        )
        predicted = predict_stack(model, holdout_data)
        for name in METHOD_NAMES:
            scores[name][holdout] = predicted[name]
        models.append({"fold": fold_index, "model": model})
        nested_maps.append({"outer_fold": fold_index, "nested": model_map})
        print(
            f"{development.cell}: completed strict outer fold {fold_index + 1}/{len(folds)}",
            flush=True,
        )
    for name, values in scores.items():
        if not np.isfinite(values).all():
            raise AssertionError(f"{development.cell}/{name}: outer OOF contains non-finite values")
    outer_map = fold_audit(development.sample_ids, development.groups, folds)
    return scores, outer_map, [{"models": models, "nested_fold_maps": nested_maps}]


def feature_schema(data: CellData) -> dict[str, Any]:
    controls, control_names = label_free_state_controls(data.subset(np.asarray([0])))
    del controls
    return {
        "positions": list(POSITIONS),
        "fixed_layer_slots": len(data.selected_layer_numbers),
        "base_probe_features": base_feature_names(len(data.selected_layer_numbers)),
        "state_control_features": control_names,
        "behavioral_features": [data.feature_names[index] for index in data.behavioral_indices],
        "candidate_features": [data.feature_names[index] for index in data.candidate_indices],
        "persistence_features": [data.feature_names[index] for index in data.persistence_indices],
        "gate_evidence_features": [data.feature_names[index] for index in data.evidence_indices],
        "phenotype_names": data.phenotype_names,
        "methods": list(METHOD_NAMES),
    }


def evaluate_cell(
    data: CellData,
    config: dict,
    output_dir: Path,
    seed: int,
) -> dict[str, Any]:
    development_indices = np.flatnonzero(data.splits == "development")
    validation_indices = np.flatnonzero(data.splits == "validation")
    development = data.subset(development_indices)
    validation = data.subset(validation_indices)
    retain = bool(config.get("serialize_crossfit_training_models", True))
    represented_phenotypes = sorted(
        {int(value) for value in development.phenotype_labels if int(value) >= 0}
    )
    phenotype_counts = {
        name: int(np.sum(development.phenotype_labels == index))
        for index, name in enumerate(development.phenotype_names)
    }
    if len(represented_phenotypes) == 1:
        phenotype_status = "single_class_partial; auxiliary CE has no pathway contrast"
    elif len(represented_phenotypes) < len(development.phenotype_names):
        phenotype_status = "multiclass_partial; at least one pathway remains unlabeled"
    else:
        phenotype_status = "three_path_partial_labels_available"

    dev_scores, outer_map, outer_training = crossfit_stack_predictions(
        development,
        config,
        stable_seed(seed, data.cell, "development_oof"),
        retain,
    )
    final_model, final_map = fit_stack_model(
        development,
        config,
        stable_seed(seed, data.cell, "validation_model"),
        f"{data.cell}/validation-model",
        retain,
    )
    val_scores = predict_stack(final_model, validation)

    stem = data.cell.replace("|", "-").casefold()
    cell_dir = output_dir / stem
    checkpoint_path = cell_dir / "checkpoint.joblib"
    fold_map_path = cell_dir / "fold_map.json"
    threshold_path = cell_dir / "threshold_candidates.json"
    scores_path = cell_dir / "public_scores.json"
    feature_path = cell_dir / "feature_manifest.json"

    checkpoint = {
        "schema_version": SCHEMA_VERSION,
        "cell": data.cell,
        "public_only": True,
        "locked_accessed": False,
        "positive_class": "HCE",
        "model_revision": data.model_revision,
        "dtype": data.dtype,
        "selected_layer_indices": data.selected_layer_indices,
        "selected_layer_numbers": data.selected_layer_numbers,
        "phenotype_auxiliary_status": phenotype_status,
        "development_phenotype_counts": phenotype_counts,
        "development_outer_models": outer_training[0]["models"],
        "validation_model_fit_on_development_only": final_model,
        "configuration": {
            "seed": int(seed),
            **{
                key: config[key]
                for key in (
                    "outer_folds",
                    "base_inner_folds",
                    "gate_inner_folds",
                    "gate_base_inner_folds",
                    "base_probe_c",
                    "expert_c",
                    "gate_c",
                    "phenotype_gate_hidden",
                    "phenotype_gate_epochs",
                    "phenotype_gate_lr",
                    "phenotype_gate_l2",
                    "phenotype_aux_weight",
                    "max_fpr",
                )
            },
            "expert_classifier": expert_classifier_configuration(config),
        },
    }
    atomic_joblib(checkpoint_path, checkpoint, compress=int(config.get("joblib_compress", 3)))

    fold_payload = {
        "schema_version": SCHEMA_VERSION,
        "cell": data.cell,
        "public_only": True,
        "locked_accessed": False,
        "group_key": "fact_key_sha256",
        "development_outer_folds": outer_map,
        "development_outer_nested_maps": outer_training[0]["nested_fold_maps"],
        "validation_model_nested_maps": final_map,
    }
    atomic_json(fold_map_path, fold_payload)

    threshold_payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "cell": data.cell,
        "public_only": True,
        "locked_accessed": False,
        "max_fpr": float(config["max_fpr"]),
        "methods": {},
    }
    score_payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "cell": data.cell,
        "public_only": True,
        "locked_accessed": False,
        "positive_class": "HCE",
        "phenotype_auxiliary_status": phenotype_status,
        "development_phenotype_counts": phenotype_counts,
        "development_protocol": "strict outer fact-group OOF through base probes, experts, and gate",
        "validation_protocol": "model fit on development only; threshold selected on validation",
        "methods": {},
    }
    for name in METHOD_NAMES:
        dev_candidates, dev_selected = enumerate_thresholds(
            development.labels, dev_scores[name], float(config["max_fpr"])
        )
        val_candidates, val_selected = enumerate_thresholds(
            validation.labels, val_scores[name], float(config["max_fpr"])
        )
        threshold_payload["methods"][name] = {
            "development_oof_candidates": dev_candidates,
            "development_oof_selected": dev_selected,
            "validation_candidates": val_candidates,
            "validation_selected_for_future_test": val_selected,
        }
        score_payload["methods"][name] = {
            "development_oof": dev_selected,
            "validation": val_selected,
            "scores": [
                {
                    "sample_id": sample_id,
                    "split": "development",
                    "label": "HCE" if label else "HCC",
                    "fact_key_sha256": str(group),
                    "score": float(score),
                }
                for sample_id, label, group, score in zip(
                    development.sample_ids,
                    development.labels,
                    development.groups,
                    dev_scores[name],
                )
            ]
            + [
                {
                    "sample_id": sample_id,
                    "split": "validation",
                    "label": "HCE" if label else "HCC",
                    "fact_key_sha256": str(group),
                    "score": float(score),
                }
                for sample_id, label, group, score in zip(
                    validation.sample_ids,
                    validation.labels,
                    validation.groups,
                    val_scores[name],
                )
            ],
        }
    atomic_json(threshold_path, threshold_payload)
    atomic_json(scores_path, score_payload)

    schema = feature_schema(data)
    schema_json = json.dumps(schema, sort_keys=True, separators=(",", ":")).encode("utf-8")
    feature_payload = {
        "schema_version": SCHEMA_VERSION,
        "cell": data.cell,
        "public_only": True,
        "locked_accessed": False,
        "feature_schema": schema,
        "feature_schema_sha256": hashlib.sha256(schema_json).hexdigest(),
        "selected_layer_indices": data.selected_layer_indices,
        "selected_layer_numbers": data.selected_layer_numbers,
        "source_sha256": data.source_hashes,
    }
    atomic_json(feature_path, feature_payload)

    artifacts = {
        str(path.relative_to(output_dir)): sha256_file(path)
        for path in (checkpoint_path, fold_map_path, threshold_path, scores_path, feature_path)
    }
    return {
        "cell": data.cell,
        "development_rows": len(development.labels),
        "validation_rows": len(validation.labels),
        "development_fact_groups": len(np.unique(development.groups)),
        "validation_fact_groups": len(np.unique(validation.groups)),
        "feature_schema_sha256": feature_payload["feature_schema_sha256"],
        "phenotype_auxiliary_status": phenotype_status,
        "development_phenotype_counts": phenotype_counts,
        "artifacts": artifacts,
        "validation": {
            name: score_payload["methods"][name]["validation"] for name in METHOD_NAMES
        },
    }


def validate_global_config(config: dict) -> None:
    if config.get("schema_version") != CONFIG_SCHEMA_VERSION:
        raise ValueError(
            f"configuration schema must be {CONFIG_SCHEMA_VERSION!r}, got {config.get('schema_version')!r}"
        )
    required = (
        "seed",
        "outer_folds",
        "base_inner_folds",
        "gate_inner_folds",
        "gate_base_inner_folds",
        "fixed_layer_count",
        "base_probe_c",
        "expert_c",
        "gate_c",
        "phenotype_gate_hidden",
        "phenotype_gate_epochs",
        "phenotype_gate_lr",
        "phenotype_gate_l2",
        "phenotype_aux_weight",
        "max_fpr",
        "cells",
    )
    missing = [key for key in required if key not in config]
    if missing:
        raise ValueError(f"configuration lacks required keys: {missing}")
    cells = [cell["cell"] for cell in config["cells"]]
    if len(cells) != len(set(cells)):
        raise ValueError("configuration contains duplicate cells")
    if len(cells) != 5:
        raise ValueError("the unified MOSAIC-v1 run must contain exactly five cells")
    if not 0.0 <= float(config["max_fpr"]) <= 1.0:
        raise ValueError("max_fpr must be in [0, 1]")
    expert_classifier_configuration(config)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--benchmark", type=Path, required=True)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="validate public inputs and common feature structure without fitting models",
    )
    args = parser.parse_args()

    for path in (args.benchmark, args.config, args.output_dir):
        assert_public_path(path)
    benchmark = read_json(args.benchmark)
    config = read_json(args.config)
    validate_global_config(config)
    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    loaded = [
        load_cell_data(
            benchmark,
            args.benchmark,
            cell_config,
            int(config["fixed_layer_count"]),
        )
        for cell_config in config["cells"]
    ]
    schemas = [feature_schema(data) for data in loaded]
    canonical_schema = json.dumps(schemas[0], sort_keys=True, separators=(",", ":"))
    for data, schema in zip(loaded[1:], schemas[1:]):
        if json.dumps(schema, sort_keys=True, separators=(",", ":")) != canonical_schema:
            raise ValueError(f"feature structure differs across cells; first mismatch is {data.cell}")

    input_manifest = {
        "schema_version": SCHEMA_VERSION,
        "configuration_schema_version": CONFIG_SCHEMA_VERSION,
        "public_only": True,
        "locked_accessed": False,
        "benchmark": str(args.benchmark),
        "benchmark_sha256": sha256_file(args.benchmark),
        "config": str(args.config),
        "config_sha256": sha256_file(args.config),
        "implementation": str(Path(__file__).resolve()),
        "implementation_sha256": sha256_file(Path(__file__).resolve()),
        "runtime_versions": {
            "python": sys.version,
            "numpy": np.__version__,
            "scikit_learn": sklearn.__version__,
            "torch": torch.__version__,
            "joblib": joblib.__version__,
        },
        "fact_group_key": "fact_key_sha256",
        "cells": [
            {
                "cell": data.cell,
                "rows": len(data.labels),
                "development_rows": int(np.sum(data.splits == "development")),
                "validation_rows": int(np.sum(data.splits == "validation")),
                "selected_layer_numbers": data.selected_layer_numbers,
                "model_revision": data.model_revision,
                "dtype": data.dtype,
                "source_sha256": data.source_hashes,
            }
            for data in loaded
        ],
        "common_feature_schema_sha256": hashlib.sha256(canonical_schema.encode("utf-8")).hexdigest(),
        "validation_only": bool(args.validate_only),
    }
    atomic_json(output_dir / "input_manifest.json", input_manifest)
    if args.validate_only:
        atomic_json(
            output_dir / "validation_only_result.json",
            {
                "schema_version": SCHEMA_VERSION,
                "public_only": True,
                "locked_accessed": False,
                "status": "all five public inputs validated; no model fitted",
                "common_feature_schema_sha256": input_manifest["common_feature_schema_sha256"],
            },
        )
        return

    cell_results = []
    for index, data in enumerate(loaded):
        result = evaluate_cell(
            data,
            config,
            output_dir,
            stable_seed(int(config["seed"]), data.cell, index),
        )
        cell_results.append(result)
        atomic_json(
            output_dir / "run_manifest.partial.json",
            {
                "schema_version": SCHEMA_VERSION,
                "public_only": True,
                "locked_accessed": False,
                "completed_cells": cell_results,
            },
        )

    schema_hashes = {result["feature_schema_sha256"] for result in cell_results}
    if len(schema_hashes) != 1:
        raise AssertionError("completed cells do not share one feature schema")
    run_manifest = {
        "schema_version": SCHEMA_VERSION,
        "public_only": True,
        "locked_accessed": False,
        "positive_class": "HCE",
        "group_key": "fact_key_sha256",
        "fit_protocol": {
            "development": "strict nested fact-group OOF",
            "validation_model": "fit on development only",
            "threshold": "validation maximum recall subject to configured FPR ceiling",
            "locked": "unsupported and not accessed",
        },
        "common_feature_schema_sha256": next(iter(schema_hashes)),
        "cells": cell_results,
    }
    run_manifest_path = output_dir / "run_manifest.json"
    atomic_json(run_manifest_path, run_manifest)
    (output_dir / "run_manifest.partial.json").unlink(missing_ok=True)

    artifacts = {}
    for path in sorted(output_dir.rglob("*")):
        if path.is_file() and path.name != "artifact_sha256.json":
            artifacts[str(path.relative_to(output_dir))] = sha256_file(path)
    atomic_json(
        output_dir / "artifact_sha256.json",
        {
            "schema_version": SCHEMA_VERSION,
            "public_only": True,
            "locked_accessed": False,
            "artifacts": artifacts,
        },
    )


if __name__ == "__main__":
    main()
