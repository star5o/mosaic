#!/usr/bin/env python3
"""Strict public-only, group-nested MOSAIC-v1 training and evaluation.

This module intentionally does not reuse the earlier MOSAIC-v1 evaluator.  It
builds every learned internal feature and every stacked prediction without
letting a held-out fact group participate in an upstream fit.

The JSON configuration makes corrected behavioral, NLI, candidate-margin, and
persistence artifacts replaceable inputs.  Every numeric field must be named
explicitly, which prevents accidental use of gold answers or review labels.
Raw internal states always come from the public ``*-public-features.pt`` files.

Development predictions use an outer StratifiedGroupKFold.  Inside each outer
training fold, layer probes are cross-fitted by fact group.  Expert predictions
used to train the gate are generated by another group fold; their internal
features are rebuilt inside that fold, so the gate holdout cannot influence a
base probe, an expert, or the gate itself.  A final model is fit on development
only and applied once to validation.  This script has no locked-test mode.
"""

